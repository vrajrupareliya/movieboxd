const updatePosters = async () => {
  try {
    await connectdb();
    const movies = await Movie.find({});
    console.log(`Found ${movies.length} movies in database.`);

    const ops = movies.map((movie) => {
      const verifiedUrl =
        posterMap[movie.title] ||
        `https://images.unsplash.com/photo-1489599849927-2ee91cede3ba?w=500&q=80&fit=crop`;

      return {
        updateOne: {
          filter: { _id: movie._id },
          update: { $set: { posterUrl: verifiedUrl } }
        }
      };
    });

    const result = await Movie.bulkWrite(ops);
    console.log(`Successfully bulk-updated ${result.modifiedCount} movie poster URLs with verified TMDB paths!`);
    process.exit(0);
  } catch (err) {
    console.error("Error updating posters:", err);
    process.exit(1);
  }
};

updatePosters();
